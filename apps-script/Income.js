// Income by the month it was earned. Some income arrives after the month it's for (say, a contractor paid on the
// 6th for the month before). The ledger keeps the day the money came; the Income sheet moves the income of the
// accounts in Settings income_lag_accounts (ids, comma-separated) back by income_lag_months, and Monthly's Income
// row (2) adds that shift, so a month's income meets its own expenses (Savings), as taxes do by accrual.
// Rows by position (Monthly reads row 2): 1 months, 2 the shift (earned − received), 3 received, 4 earned.

const INCOME_SHEET_ = 'Income';

function shiftMonth_(m, n) {
  let y = Number(m.slice(0, 4));
  let mo = Number(m.slice(5, 7)) + n;
  while (mo < 1) { mo += 12; y--; }
  while (mo > 12) { mo -= 12; y++; }
  return y + '-' + (mo < 10 ? '0' : '') + mo;
}

/** p: { txs, settings, today }. Per month (USD): received on the lagging accounts, earned, and the shift. */
function computeIncomeShift_(p) {
  const s = p.settings || {};
  const ids = String(s.income_lag_accounts || '').split(/[,\s]+/).filter(Boolean);
  const lag = Number(s.income_lag_months) > 0 ? Math.round(Number(s.income_lag_months)) : 1;
  const months = monthsBetween_(String(s.history_start || p.today.slice(0, 4) + '-01-01').slice(0, 10), p.today);
  const zero = () => { const o = {}; months.forEach(m => { o[m] = 0; }); return o; };
  const received = zero();
  const earned = zero();
  p.txs.forEach(t => {
    if (t.deleted || t.type !== 'income' || !t.date || ids.indexOf(t.account_id) < 0) return;
    const usd = Number(t.amount_usd) || 0;
    const m = t.date.slice(0, 7);
    if (received[m] !== undefined) received[m] += usd;
    const e = shiftMonth_(m, -lag);
    if (earned[e] !== undefined) earned[e] += usd;
  });
  const shift = {};
  months.forEach(m => { shift[m] = Math.round((earned[m] - received[m]) * 100) / 100; });
  return { months, ids, lag, received, earned, shift };
}

function writeIncomeSheet_(r, accountNames) {
  const ss = SpreadsheetApp.getActive();
  const sh = ss.getSheetByName(INCOME_SHEET_) || ss.insertSheet(INCOME_SHEET_);
  const cols = 1 + r.months.length;
  const monthDate = m => '=DATE(' + Number(m.slice(0, 4)) + ',' + Number(m.slice(5, 7)) + ',1)';
  const row = (label, map) => [label].concat(r.months.map(m => (map ? Math.round(map[m] * 100) / 100 : '')));
  const who = accountNames.length ? accountNames.join(', ') : 'none (Settings: income_lag_accounts)';
  const rows = [
    ['Line'].concat(r.months.map(monthDate)),
    row('Shift to the month earned, $', r.shift),
    row('Received (the day it came), $', r.received),
    row('Earned (the month it is for), $', r.earned),
    row('', null),
    row('Generated by the script (Income.js) after changes. Accounts: ' + who + ', paid ' + r.lag + ' month(s) after the month earned.', null),
    row('Monthly: Income (row 2) adds the shift, so Savings is by the month earned; the category rows stay by the day received.', null),
  ];
  sh.clearContents();
  if (sh.getMaxColumns() < cols) sh.insertColumnsAfter(sh.getMaxColumns(), cols - sh.getMaxColumns());
  sh.getRange(1, 1, rows.length, cols).setValues(rows);
  sh.getRange(1, 2, 1, cols - 1).setNumberFormat('mmm yy');
  sh.getRange(2, 2, 3, cols - 1).setNumberFormat('$#,##0;-$#,##0;–');
  sh.setFrozenRows(1);
  sh.setFrozenColumns(1);
}

function refreshIncome_(ledger) {
  const l = ledger || loadLedger_();
  const r = computeIncomeShift_({
    txs: l.txs,
    settings: l.settings,
    today: Utilities.formatDate(new Date(), tz_(), 'yyyy-MM-dd'),
  });
  const names = l.accounts.filter(a => r.ids.indexOf(a.id) >= 0).map(a => a.name);
  writeIncomeSheet_(r, names);
  return r;
}
